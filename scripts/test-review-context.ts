import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { initialWorkspace, applyCommand } from '../lib/domain';
import { buildReviewContext, conflictDetails, PACKET_SHA256 } from '../lib/review-context';
import { LocalDatabase } from '../lib/database';
import { commandFingerprint, executeCommand, loadCommandReceipt, loadWorkspace } from '../lib/repository';
import type { Command } from '../lib/contracts';
import packet from '../data/packet.json';

async function main() {
  const untouched = initialWorkspace();
  const freshCoverage = buildReviewContext(untouched, 'st-01', { issueId: 'duplicate-mileage' }).coverage;
  assert.deepEqual(freshCoverage, { documents: { completed: 0, total: 74 }, areas: { completed: 0, total: 13 }, outsideFilings: { completed: 0, total: 5 }, verifications: 0 }, 'An untouched workspace must expose seeded completeness obligations without first saving a command.');
  assert.equal(untouched.workpaper, undefined, 'Coverage projection cannot seed durable state as a side effect.');
  let withCoverage = applyCommand(untouched, { type: 'workflow', action: 'document_disposition', payload: { documentId: 'D23', status: 'unused', reason: 'Acceptance coverage fixture: reviewed duplicate evidence disposition.' } }, 'st-01');
  withCoverage = applyCommand(withCoverage, { type: 'workflow', action: 'review_area', payload: { area: 'Business and books to tax', status: 'reviewed', note: 'Acceptance fixture: source and independent bridge inspected.' } }, 'st-01');
  withCoverage = applyCommand(withCoverage, { type: 'workflow', action: 'verify_value', payload: { ref: 'ev-0226', method: packet.firm.starter_standards.verification_types[0], note: 'Acceptance fixture: printed field inspected.' } }, 'st-01');
  withCoverage = applyCommand(withCoverage, { type: 'workflow', action: 'outside_filing', payload: { filingId: 'fbar', status: 'prepared_elsewhere', responsible: 'Acceptance fixture separate adviser', body: 'Acceptance fixture: responsibility and conclusion documented.' } }, 'st-01');
  const progressed = buildReviewContext(withCoverage, 'st-01', { issueId: 'duplicate-mileage' }).coverage;
  assert.equal(progressed.documents.completed, 1);
  assert.equal(progressed.areas.completed, 1);
  assert.equal(progressed.verifications, 1);
  assert.deepEqual(progressed.outsideFilings, { completed: 1, total: 5 });
  assert.deepEqual(buildReviewContext(withCoverage, 'cu-01', { issueId: 'duplicate-mileage' }).coverage, progressed, 'Coverage is numeric-only and safe for the evaluator client view.');
  const customFiling = applyCommand(withCoverage, { type: 'workflow', action: 'outside_filing', payload: { title: 'Acceptance fixture additional obligation', status: 'pending', responsible: 'Acceptance fixture adviser', body: 'Acceptance fixture additional identified filing remains open.' } }, 'st-01');
  assert.deepEqual(buildReviewContext(customFiling, 'st-01', { issueId: 'duplicate-mileage' }).coverage.outsideFilings, { completed: 1, total: 6 }, 'Additional identified outside filings cannot disappear from coverage.');
  let state = applyCommand(initialWorkspace(), { type: 'accept_adjustment', issueId: 'duplicate-mileage', reason: 'Independent acceptance: duplicate scan compared with unique printed pages.' }, 'st-01');
  state = applyCommand(state, { type: 'add_note', issueId: 'duplicate-mileage', body: 'Internal staff review note for scoped response acceptance.' }, 'st-02');
  const saved = JSON.stringify(state);
  const context = buildReviewContext(state, 'st-01', { issueId: 'duplicate-mileage', sinceRevision: 0 });
  assert.equal(context.token.packetSha256, PACKET_SHA256);
  assert.equal(context.token.editRevision, state.revision);
  assert.equal(context.token.contentRevision, state.revision);
  assert(context.documents.some(document => document.document.id === 'D23' && document.document.pages.some(page => page.page === 3)));
  assert(context.evidence.some(evidence => evidence.ref === 'ev-0226' && evidence.field));
  assert(context.checks.some(check => check.id === 'unique-mileage' && check.independentValue === 8100));
  assert.equal(context.decisions.adjustments.length, 1);
  assert(context.permittedActions.includes('undo_adjustment'));
  assert(context.changes.changedRefs.includes('SchC.9'));
  assert(context.changes.changedRefs.includes('workspace:content'));
  assert.equal(JSON.stringify(state), saved, 'Query construction must not mutate captured review state.');
  const line = buildReviewContext(state, 'st-01', { ref: 'line:v3:SchC.9' });
  assert.equal(line.computation?.root, 'SchC.9');
  assert(line.decisions.adjustments.some(adjustment => adjustment.issueId === 'duplicate-mileage'), 'A direct line view must retain source-related saved decisions.');
  const client = buildReviewContext(state, 'cu-01', { issueId: 'duplicate-mileage' });
  assert.equal(client.decisions.notes.length, 0);
  assert.equal(client.decisions.adjustments.length, 0);
  assert.equal(client.permittedActions.length, 0);
  assert(!JSON.stringify(client).includes('Internal staff review note'));
  assert.equal(client.accessMode, 'local-evaluator-sandbox');
  const noClearance = buildReviewContext(state, 'st-04', { issueId: 'provider-identifier' });
  assert(!/\b\d{2}-\d{7}\b/.test(JSON.stringify(noClearance)), 'Passive context cannot expose raw provider identifiers.');
  assert.throws(() => buildReviewContext(state, 'st-01', { ref: 'line:v1:SchC.9', version: 'v3' }), /must agree/);
  assert.equal(buildReviewContext(state, 'st-01', { ref: 'line:v1:SchC.9', version: 'v1' }).permittedActions.length, 0, 'Historical engine context must never imply that v3-bound commands write that version.');
  assert.throws(() => buildReviewContext(state, 'st-01', { ref: 'unknown-evidence' }), /unavailable/);
  assert.throws(() => buildReviewContext(state, 'st-01', { sinceRevision: state.revision + 1 }), /existing change revision/);
  const activity = applyCommand(state, { type: 'workflow', action: 'mark_seen' }, 'st-01');
  const afterActivity = buildReviewContext(activity, 'st-01', { issueId: 'duplicate-mileage', sinceRevision: state.revision });
  assert.equal(afterActivity.token.contentRevision, state.revision);
  assert.equal(afterActivity.token.editRevision, state.revision + 1);
  assert.deepEqual(afterActivity.changes.changedRefs, ['workspace:activity']);
  assert.equal(conflictDetails(activity, state.revision, 'st-01').contentRevision, state.revision);
  const replayEvent = packet.timeline.find(event => Date.parse(event.at) > Date.parse(packet.return_versions[0].computed_at) && Date.parse(event.at) < Date.parse(packet.return_versions[2].computed_at))!;
  assert(replayEvent);
  const replay = applyCommand(activity, { type: 'workflow', action: 'set_replay', payload: { eventId: replayEvent.id } }, 'st-01');
  const historical = buildReviewContext(replay, 'st-01', { issueId: 'duplicate-mileage', version: 'v1' });
  assert.equal(historical.token.replay?.readOnly, true);
  assert.equal(historical.permittedActions.length, 0);
  assert.match(historical.disclaimer, /not rewound or backdated/);
  assert.throws(() => buildReviewContext(replay, 'st-01', { issueId: 'duplicate-mileage', version: 'v3' }), /not yet available/);
  const leftReplay = applyCommand(replay, { type: 'workflow', action: 'set_replay', payload: { eventId: null } }, 'st-01');
  assert.equal(buildReviewContext(leftReplay, 'st-01', { issueId: 'duplicate-mileage' }).token.replay, null);
  assert.equal(leftReplay.audit.at(-1)?.material, false);
  assert.equal(leftReplay.audit.at(-1)?.type, 'workflow:set_replay');
  assert.throws(() => applyCommand(replay, { type: 'workflow', action: 'set_replay', payload: { eventId: null } }, 'cu-01'), /firm team/);

  const directory = mkdtempSync(path.join(tmpdir(), 'miraflores-receipts-'));
  const db = new LocalDatabase(directory);
  const owner = 'isolated-receipt-test';
  const note: Command = { type: 'add_note', body: 'Receipt regression: commit exactly once after an uncertain response.' };
  const execute = (revision: number, command: Command, requestId?: string, actorId = 'st-01') => executeCommand(owner, actorId, revision, command, undefined, [], { requestId, database: db });
  try {
    assert.equal(commandFingerprint(0, { type: 'add_note', body: 'x' }), commandFingerprint(0, { body: 'x', type: 'add_note' }), 'Object key order must not change a request binding.');
    const first = await execute(0, note, 'request-stable-001');
    const retry = await execute(0, note, 'request-stable-001');
    assert.deepEqual(retry, first);
    assert.equal((await loadWorkspace(owner, db)).audit.length, 1, 'A repeated request cannot duplicate audit or notes.');
    await assert.rejects(execute(0, { ...note, body: 'Different command content.' }, 'request-stable-001'), /identity conflict/);
    await assert.rejects(execute(1, note, 'request-stable-001'), /identity conflict/, 'Changing the captured revision changes the original request.');
    assert.equal(await loadCommandReceipt('other-owner', 'st-01', 'request-stable-001', db), null);
    assert.equal(await loadCommandReceipt(owner, 'st-02', 'request-stable-001', db), null);
    const second = await execute(first.revision, { type: 'add_note', body: 'A later distinct operation.' }, 'request-next-002');
    const oldRetry = await execute(0, note, 'request-stable-001');
    assert.equal(oldRetry.revision, first.revision, 'A receipt returns its original committed result, not unrelated later work.');
    assert.equal((await loadWorkspace(owner, db)).revision, second.revision);
    await assert.rejects(execute(0, note, 'request-stale-003'), /changed this workspace/);
    assert.equal(await loadCommandReceipt(owner, 'st-01', 'request-stale-003', db), null, 'A rejected stale action cannot acquire a committed receipt.');
    const race = await Promise.all([execute(second.revision, note, 'request-race-004'), execute(second.revision, note, 'request-race-004')]);
    assert.deepEqual(race[0], race[1]);
    const afterRace = await loadWorkspace(owner, db);
    assert.equal(afterRace.revision, second.revision + 1);
    assert.equal(afterRace.notes.length, second.notes.length + 1);
    await assert.rejects(execute(afterRace.revision, note, 'request-client-005', 'cu-01'), /Only tax/);
    assert.equal(await loadCommandReceipt(owner, 'cu-01', 'request-client-005', db), null);
    await assert.rejects(executeCommand(owner, 'st-01', afterRace.revision, note, undefined,
      [{ sql: 'INSERT INTO nonexistent_acceptance_table (id) VALUES (?)', args: ['fail-intentionally'] }], { requestId: 'request-rollback-006', database: db }), /no such table/);
    assert.equal((await loadWorkspace(owner, db)).revision, afterRace.revision, 'A related SQL failure rolls back the state and audit.');
    assert.equal(await loadCommandReceipt(owner, 'st-01', 'request-rollback-006', db), null, 'A related SQL failure rolls back receipt insertion too.');
    const snapshot = db.readSnapshot([{ sql: 'SELECT revision FROM workspaces WHERE owner_id = ?', args: [owner] }, { sql: 'SELECT revision FROM command_receipts WHERE owner_id = ? ORDER BY revision', args: [owner] }]);
    assert.equal(snapshot[0][0].revision, afterRace.revision);
    assert.equal(snapshot[1].length, 3);
  } finally { db.close(); rmSync(directory, { recursive: true, force: true }); }
  console.log('Review context and receipt regressions passed: captured provenance/revisions, masking/client scope, replay, material/activity conflicts, exact-once retries, actor/owner/body binding, CAS race, SQL rollback and snapshot reads.');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
